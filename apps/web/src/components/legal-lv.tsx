/*
 * The institutional pages of the Latvian market (`/lv/juridiska-informacija`, `/lv/privatums`,
 * `/lv/lietosanas-noteikumi`, `/lv/pieklustamiba`, `/lv/dati`), written for Latvian law: the
 * French texts cite the LCEN, the CNIL and the RGAA, none of which applies there. They print the
 * same `LEGAL_*` facts, with the same `{{…}}` placeholders while one is unknown. The legal
 * information identifies the provider as section 4 of the Law on Information Society Services
 * (Informācijas sabiedrības pakalpojumu likums) asks; the hosting provider appears among the
 * processors of the privacy page, which says only that it is in the European Economic Area.
 *
 * A GP practice's page names the GPs who work there, as the National Health Service publishes
 * them: the privacy page carries the article 14 notice those GPs are owed.
 */

const actionLink = `${linkStyles()} inline-flex min-h-11 items-center text-body font-semibold`;

/**
 * How to lodge a complaint with the Data State Inspectorate (Datu valsts inspekcija), whose
 * address (Elijas iela 17, Rīga, LV-1050) and e-mail (pasts@dvi.gov.lv) were checked on
 * dvi.gov.lv on 2026-11-27.
 */
const DVI_COMPLAINT = "https://www.dvi.gov.lv/lv/iesniegumu-paraugi";

/** The credit the State Land Service asks for the address register's data, word for word. */
const VAR_CREDIT = "Izmantoti Valsts adrešu reģistra informācijas sistēmas dati";

/** The CC0 1.0 deed, in Latvian, when a source names no licence page. */
const CC0_DEED = "https://creativecommons.org/publicdomain/zero/1.0/deed.lv";

/** The licence of a Latvian source, as the data page names it (CC0 1.0 or CC BY 4.0). */
function licenceOf(licence: string | undefined): "cc0" | "ccBy" {
	return licence?.includes("CC BY") ? "ccBy" : "cc0";
}

type LvHref =
	| "/mentions-legales"
	| "/confidentialite"
	| "/conditions"
	| "/accessibilite"
	| "/donnees";

/** The shared frame: cover (with the draft mark until the legal review), booklet, trail. */
async function LvFrame({
	locale,
	href,
	title,
	lead,
	mark,
	note,
	children,
}: {
	locale: Locale;
	href: LvHref;
	title: string;
	lead: string;
	mark?: string;
	note?: string | null;
	children: React.ReactNode;
}) {
	return (
		<PublicPage locale={locale} href={href}>
			<InstitutionalCover title={title} lead={lead} mark={mark} note={note} />
			<BookletPage>
				<PageGraph locale={locale} href={href} name={title} trail={[{ label: title, href }]} />
				<Trail locale={locale} items={[{ label: title, href }]} />
				{children}
			</BookletPage>
		</PublicPage>
	);
}

/** A configured date in the locale's long form, or its placeholder. */
async function longDate(locale: Locale, fact: LegalValue): Promise<LegalValue> {
	if (fact.missing) return fact;
	const format = await getFormatter({ locale });
	return {
		value: format.dateTime(new Date(`${fact.value}T12:00:00Z`), { dateStyle: "long" }),
		missing: false,
	};
}

/** Every source with its publisher and its attribution, word for word. */
async function SourceAttributions({ locale }: { locale: Locale }) {
	const tSite = await getTranslations({ locale, namespace: "Site" });
	const external = tSite("externalLink");
	return (
		<ul className="flex flex-col gap-3 border-t border-rule-soft pt-3">
			{latvia.registries.map((source) => (
				<li key={source.id} className="flex flex-col gap-1 text-body text-ink">
					<ExternalLink href={source.url} externalLabel={external}>
						{source.name}
					</ExternalLink>
					<span className="text-meta text-ink-muted">{source.publisher}</span>
					<span data-attribution={source.id} className="text-meta text-ink" lang="lv">
						{source.attribution}
					</span>
				</li>
			))}
		</ul>
	);
}

