/** Letters NFD does not decompose, folded to the Latin letters people type instead. */
const LETTER_FOLDS: Readonly<Record<string, string>> = {
	ø: "o",
	æ: "ae",
	œ: "oe",
	ł: "l",
	đ: "d",
	ð: "d",
	þ: "th",
	ı: "i",
	ħ: "h",
};

/**
 * Letters also commonly spelled out when typed without them: German umlauts
 * ("Muenchen", "Koeln"), the Scandinavian å and ø ("Aalesund", "Tromsoe").
 */
const SPELLED_OUT_LETTERS: Readonly<Record<string, string>> = {
	ä: "ae",
	ö: "oe",
	ü: "ue",
	å: "aa",
	ø: "oe",
};

/**
 * A place name reduced to the form typed names are compared in: lowercase,
 * without diacritics, "ß" as "ss", and anything but letters and digits
 * (apostrophes, hyphens, dots, commas, parentheses) as single spaces.
 */
export function placeKey(text: string): string {
	return text
		.toLowerCase()
		.replace(/ß/g, "ss")
		.normalize("NFD")
		.replace(/\p{M}/gu, "")
		.replace(/[øæœłđðþıħ]/g, (letter) => LETTER_FOLDS[letter] ?? letter)
		.replace(/[^\p{L}\p{N}]+/gu, " ")
		.trim();
}

/** Every key a listed name is found under: its own, and its spelled-out umlaut form when it has one. */
export function placeKeysOf(name: string): string[] {
	const keys = new Set([placeKey(name)]);
	const lower = name.normalize("NFC").toLowerCase();
	if (/[äöüåø]/.test(lower)) {
		keys.add(
			placeKey(lower.replace(/[äöüåø]/g, (letter) => SPELLED_OUT_LETTERS[letter] ?? letter)),
		);
	}
	keys.delete("");
	return [...keys];
}

type CountryPlace = Extract<EuropeanPlace, { kind: "country" }>;
type CityPlace = Extract<EuropeanPlace, { kind: "city" }>;

interface PlaceIndex {
	byCode: Map<string, EuropeanCountry>;
	/** Countries by the key of any of their names, aliases or "covered" phrases. */
	countries: Map<string, CountryPlace>;
	/** Cities by key, in the order of EUROPEAN_COUNTRIES: the first is the one a bare name means. */
	cities: Map<string, CityPlace[]>;
}

let placeIndex: PlaceIndex | undefined;

function buildIndex(): PlaceIndex {
	const byCode = new Map<string, EuropeanCountry>();
	const countries = new Map<string, CountryPlace>();
	const cities = new Map<string, CityPlace[]>();
	for (const country of EUROPEAN_COUNTRIES) {
		byCode.set(country.code, country);
		const place: CountryPlace = { kind: "country", country };
		const countryNames = [
			...Object.values(country.names),
			...Object.values(country.covered),
			...country.aliases,
		];
		for (const name of countryNames) {
			for (const key of placeKeysOf(name)) {
				if (!countries.has(key)) countries.set(key, place);
			}
		}
		for (const names of country.cities) {
			const city: CityPlace = { kind: "city", country, city: names[0] ?? "" };
			for (const name of names) {
				for (const key of placeKeysOf(name)) {
					const entries = cities.get(key) ?? [];
					if (entries.some((entry) => entry.country === country)) continue;
					entries.push(city);
					cities.set(key, entries);
				}
			}
		}
	}
	return { byCode, countries, cities };
}

function index(): PlaceIndex {
	placeIndex ??= buildIndex();
	return placeIndex;
}

/** A token that can be (part of) a postcode: digits, possibly with letters ("10115", "sw1a", "d02"). */
const POSTCODE_TOKEN = /^[a-z]*\d[a-z\d]*$/;
/** A country prefix before a postcode ("D-10115", "LV-1050"). */
const POSTCODE_PREFIX = /^[a-z]{1,3}$/;
/** The two letters ending a Dutch postcode ("1012 AB Amsterdam"). */
const POSTCODE_SUFFIX = /^[a-z]{2}$/;
/** Digits a postcode has at least, so "Paris 15" or "Lyon 3e" keep their number. */
const POSTCODE_MIN_DIGITS = 3;

const digitCount = (tokens: readonly string[]) => tokens.join("").replace(/\D/g, "").length;

/** The input's tokens, then the same without a leading or trailing postcode, least stripped first. */
function candidateTokens(tokens: readonly string[]): (readonly string[])[] {
	const candidates: (readonly string[])[] = [tokens];

	let start = POSTCODE_PREFIX.test(tokens[0] ?? "") && POSTCODE_TOKEN.test(tokens[1] ?? "") ? 1 : 0;
	const postcodeStart = start;
	while (start < tokens.length && POSTCODE_TOKEN.test(tokens[start] ?? "")) start++;
	if (
		start > postcodeStart &&
		digitCount(tokens.slice(postcodeStart, start)) >= POSTCODE_MIN_DIGITS
	) {
		const rest = tokens.slice(start);
		candidates.push(rest);
		if (POSTCODE_SUFFIX.test(rest[0] ?? "")) candidates.push(rest.slice(1));
	}

	let end = tokens.length;
	while (end > 0 && POSTCODE_TOKEN.test(tokens[end - 1] ?? "")) end--;
	if (end < tokens.length && digitCount(tokens.slice(end)) >= POSTCODE_MIN_DIGITS) {
		const rest = tokens.slice(0, end);
		candidates.push(rest);
		if (POSTCODE_PREFIX.test(rest.at(-1) ?? "")) candidates.push(rest.slice(0, -1));
	}

	return candidates.filter((candidate) => candidate.length > 0);
}

/** The place some tokens name: a country, a city, or a city followed by its own country. */
function placeOfTokens(tokens: readonly string[], { countries, cities }: PlaceIndex) {
	const key = tokens.join(" ");
	const place = countries.get(key) ?? cities.get(key)?.[0];
	if (place) return place;
	// "Berlin, Allemagne", "München (Deutschland)", "Brest Biélorussie".
	for (let cut = 1; cut < tokens.length; cut++) {
		const named = countries.get(tokens.slice(cut).join(" "));
		if (!named) continue;
		const city = cities
			.get(tokens.slice(0, cut).join(" "))
			?.find((entry) => entry.country === named.country);
		if (city) return city;
	}
	return undefined;
}

/**
 * What a typed place names: a country (by any of its names or aliases) or one
 * of the listed cities; null otherwise. The whole input must be the name, up
 * to case, diacritics and punctuation ("Berlinerstrasse" is not Berlin), with
 * a leading or trailing postcode allowed ("10115 Berlin") and the city's own
 * country after it ("Berlin, Allemagne"). A name of both a country and a city
 * ("Luxembourg", "Monaco") names the country.
 */
export function europeanPlaceOf(text: string): EuropeanPlace | null {
	const key = placeKey(text);
	if (key === "") return null;
	const places = index();
	for (const tokens of candidateTokens(key.split(" "))) {
		const place = placeOfTokens(tokens, places);
		if (place) return place;
	}
	return null;
}

/**
 * True when `text` is, as a whole, one of the listed cities of the country `code` under any of
 * its names ("Vilnius", "Wilno" for `LT`; "Bergen" for `NO`), whichever country a bare name
 * means first: a city's market ranks it over its smaller homonyms (a village "Vilnius").
 */
export function isEuropeanCityOf(text: string, code: string): boolean {
	const key = placeKey(text);
	const country = code.toUpperCase();
	return (
		key !== "" &&
		(index()
			.cities.get(key)
			?.some((entry) => entry.country.code === country) ??
			false)
	);
}

/** The country of an ISO 3166-1 alpha-2 code ("DE", "de"; "XK" for Kosovo), or undefined. */
export function europeanCountry(code: string): EuropeanCountry | undefined {
	return index().byCode.get(code.toUpperCase());
}
