/**
 * European countries and their largest cities, as people type them. The site
 * search uses it to move a search to the market of a country typed alone
 * ("Allemagne", "Deutschland" → `/de`), and to recognise a place in a country
 * Apercura does not cover yet ("Warszawa", "Pologne", "Bruxelles") and say so in
 * the visitor's language. Plain data and pure functions, no I/O.
 */

/** The interface languages a country's name is given in. */
export type GeoLanguage =
	| "en"
	| "fr"
	| "de"
	| "es"
	| "it"
	| "cs"
	| "et"
	| "pl"
	| "nb"
	| "fi"
	| "lt"
	| "sl"
	| "el"
	| "lv"
	| "sv";

export interface EuropeanCountry {
	/** ISO 3166-1 alpha-2, uppercase ("DE"; the UK is "GB"). */
	code: string;
	/** The country's name in each interface language, nominative, as shown alone in a list ("Allemagne", "Deutschland", "Německo"). */
	names: Record<GeoLanguage, string>;
	/**
	 * The name as the direct object of "Apercura does not cover … yet" in each
	 * language, with the article the language needs ("the Netherlands",
	 * "l’Allemagne", "die Schweiz", "los Países Bajos", "i Paesi Bassi"), and in
	 * the accusative in Czech ("Francii", "Ukrajinu"), the genitive in Lithuanian, which a negation
	 * governs ("Prancūzijos", "Latvijos"), and in the nominative in Polish, which says it
	 * after a colon ("kraju: Francja"), and in the genitive in Slovenian, which a negated verb
	 * governs ("Apercura še ne pokriva Poljske"), and in the locative in Latvian, whose sentence is
	 * "Apercura vēl nav pieejama …" ("Francijā", "Lielbritānijā"; "Monako" does not decline).
	 */
	covered: Record<GeoLanguage, string>;
	/** Other names people type: native names in each official language, short and old forms. No ISO codes. */
	aliases: readonly string[];
	/** The largest cities, each as all the names people type: the native name first, then exonyms and transliterations. */
	cities: readonly (readonly string[])[];
}

/** What a typed place names: a country, or one of the listed cities of a country. */
export type EuropeanPlace =
	| { kind: "country"; country: EuropeanCountry }
	| {
			kind: "city";
			country: EuropeanCountry;
			city: string /* the native name, first of its list */;
	  };

